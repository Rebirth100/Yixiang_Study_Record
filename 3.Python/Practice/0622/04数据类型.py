# 变量：程序运行过程中，存储数据的单元

# 整形

a = 30
print(a, type(a))
b = 20
print(b, type(b))

# 浮点型
e = 3.14
print(e, type(e))
f = 2e3
print(f, type(f))

# 复数
g = 20 + 30J
print(g, type(g))

print(g.real, g.imag)
