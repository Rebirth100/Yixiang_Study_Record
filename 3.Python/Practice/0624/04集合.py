#集合(set):无序的数据集合，没有索引，值是唯一的，不能重复



#1、创建
s1= {"True",1,0,False}
print(s1)
#2、转换
s2= set("Happy")
print(s2)
#3、添加
s3 = {"Frank","Rose","Jerry"}
s3.add("Emily")
print(s3)
#4、修改
s3.update("Judy","Jackie")
print(s3)
#5、删除
s3.pop()
s3.remove("Emily")
print(s3)
